"""OCR a scanned PDF (no text layer) into a searchable .txt for RAG ingestion.

Usage: python scripts/rag_kb/ocr_pdf.py <input.pdf> [--out <output.txt>] [--dpi 200] [--start N] [--end M]

Renders each page with PyMuPDF, recognises text with RapidOCR (Chinese-capable),
and writes line-ordered text next to the PDF. Skip --start/--end to OCR the whole
file; useful for a quick sanity check on one page first.
"""

import argparse
import sys
from pathlib import Path

import fitz
import numpy as np
from rapidocr_onnxruntime import RapidOCR


def page_to_ocr_image(page, dpi: int) -> np.ndarray:
    pix = page.get_pixmap(dpi=dpi)
    img = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, pix.n)
    rgb = img[:, :, :3]
    return rgb[:, :, ::-1].copy()  # RGB -> BGR (OpenCV convention for RapidOCR)


def ocr_pdf(pdf_path: Path, out_path: Path, dpi: int, start: int, end: int) -> int:
    engine = RapidOCR()
    doc = fitz.open(str(pdf_path))
    pages = range(start, end + 1)
    total = len(doc)
    n_chars = 0
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(f"# OCR of {pdf_path.name} — generated by scripts/rag_kb/ocr_pdf.py\n\n")
        for i in pages:
            if i >= total:
                break
            page = doc[i]
            img = page_to_ocr_image(page, dpi)
            result, _ = engine(img)
            lines = [ln[1] for ln in (result or [])]
            text = "\n".join(lines).strip()
            n_chars += len(text)
            fh.write(f"\n===== 第 {i + 1} 页 / page {i + 1} =====\n{text}\n")
            print(f"  page {i + 1}/{total}: {len(text)} chars", flush=True)
    doc.close()
    return n_chars


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("pdf", help="path to the scanned PDF")
    ap.add_argument("--out", help="output .txt path (default: same name as PDF)")
    ap.add_argument("--dpi", type=int, default=200)
    ap.add_argument("--start", type=int, default=0, help="0-based first page")
    ap.add_argument("--end", type=int, default=10**9, help="0-based last page (inclusive)")
    args = ap.parse_args()

    pdf = Path(args.pdf)
    out = Path(args.out) if args.out else pdf.with_suffix(".txt")
    chars = ocr_pdf(pdf, out, args.dpi, args.start, args.end)
    print(f"\nDone: {out} — {chars} characters extracted.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
